CREATE TABLE data_quality_flag (
    flag_id INTEGER PRIMARY KEY,
    run_id TEXT NOT NULL,
    source_id TEXT NOT NULL,
    record_id TEXT,
    flag_row_number INTEGER NOT NULL CHECK(flag_row_number>0),
    scope TEXT NOT NULL CHECK(scope IN ('dataset','field','record_check','record')),
    source_file TEXT NOT NULL,
    source_sha256 TEXT NOT NULL,
    source_row_number TEXT NOT NULL,
    field TEXT NOT NULL,
    rule_id TEXT NOT NULL,
    flag TEXT NOT NULL,
    status TEXT NOT NULL,
    raw_value TEXT NOT NULL,
    reason TEXT NOT NULL,
    UNIQUE(run_id,flag_row_number),
    CHECK((scope='dataset' AND record_id IS NULL AND source_row_number='') OR
          (scope!='dataset' AND record_id IS NOT NULL AND source_row_number!='')),
    FOREIGN KEY(run_id,source_id) REFERENCES run_dataset(run_id,source_id),
    FOREIGN KEY(record_id,run_id,source_id) REFERENCES source_record(record_id,run_id,source_id)
) STRICT;
