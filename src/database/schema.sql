-- Phase 3 schema v1. Exact decimals are TEXT, never REAL/NUMERIC.
CREATE TABLE schema_version (
    version INTEGER PRIMARY KEY CHECK(version = 1),
    schema_sha256 TEXT NOT NULL
) STRICT;
CREATE TABLE dataset_source (
    source_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    domain TEXT NOT NULL CHECK(domain IN ('accounting','sales'))
) STRICT;
CREATE TABLE processing_run (
    run_id TEXT PRIMARY KEY,
    schema_version INTEGER NOT NULL REFERENCES schema_version(version),
    ingested_at TEXT NOT NULL,
    manifest_sha256 TEXT NOT NULL,
    validation_sha256 TEXT NOT NULL,
    flags_sha256 TEXT NOT NULL,
    manifest_json TEXT NOT NULL CHECK(json_valid(manifest_json)),
    validation_json TEXT NOT NULL CHECK(json_valid(validation_json)),
    approval_json TEXT NOT NULL CHECK(json_valid(approval_json))
) STRICT;
CREATE TABLE run_dataset (
    run_id TEXT NOT NULL REFERENCES processing_run(run_id),
    source_id TEXT NOT NULL REFERENCES dataset_source(source_id),
    source_file TEXT NOT NULL,
    source_sha256 TEXT NOT NULL CHECK(length(source_sha256)=64),
    processed_file TEXT NOT NULL,
    processed_sha256 TEXT NOT NULL CHECK(length(processed_sha256)=64),
    expected_rows INTEGER NOT NULL CHECK(expected_rows>0),
    output_schema_json TEXT NOT NULL CHECK(json_valid(output_schema_json)),
    PRIMARY KEY(run_id,source_id)
) STRICT;
CREATE TABLE source_record (
    record_id TEXT PRIMARY KEY CHECK(length(record_id)=64),
    run_id TEXT NOT NULL,
    source_id TEXT NOT NULL,
    source_row_number INTEGER NOT NULL CHECK(source_row_number>0),
    processed_row_number INTEGER NOT NULL CHECK(processed_row_number>0),
    UNIQUE(run_id,source_id,source_row_number),
    UNIQUE(run_id,source_id,processed_row_number),
    UNIQUE(record_id,run_id,source_id),
    FOREIGN KEY(run_id,source_id) REFERENCES run_dataset(run_id,source_id)
) STRICT;
